"""Is the constant-threshold family COMPLETE?

The paper builds everything on rules of the form tau = inf{t : Rhat(t) <= ell},
one parameter.  It never asks whether a cleverer predictor-adapted rule could
reach a point strictly inside that family's frontier.  If one can, the whole
geometric picture describes a sub-family rather than the achievable set, and the
"frontier" is not a frontier.

Derivation first.  At the optimum with value L, Dinkelbach says the optimal rule
minimises the LINEAR functional chi*Pr(tau>=T) + (L/Tbar)*E[(T-tau)^+].  Waiting dt
buys a waste reduction of dt, worth L/Tbar, at a failure risk h(t|F_t)dt worth chi.
So the optimal rule is

    stop when  chi * h(t | F_t)  >=  L / Tbar,

i.e. in unnormalised terms (c_f - c_p) h = g: stop when the instantaneous risk cost
rate reaches the long-run cost rate.  With trivial information this is exactly the
Barlow-Proschan condition r(t)*int_0^t Rbar - F(t) = c_p/(c_f-c_p).

So the frontier is generated by thresholding the CONDITIONAL HAZARD, not the
predicted life.  Thresholding Rhat is optimal only if Rhat is a monotone transform
of that hazard along paths.  Two things to check, and the second can refute the
paper:

  (1) the reduction to Barlow-Proschan, on a Weibull where both sides are exact;
  (2) whether enriching the rule class finds points strictly inside the constant
      threshold frontier on the real fleets.  Enrichments: a time-varying boundary
      alpha + beta*t, and a boundary using the local slope of the predictor.
"""
